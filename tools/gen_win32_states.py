#!/usr/bin/env python3
"""Writes xbox/win32/XD3DStates.inc: for each Xbox D3DRS_*/D3DTSS_* (RXDK's
d3d8types.h, as copied into xbox/win32/include) the Direct3D 9 state of the
same name (d3d9types.h), for xbox/win32/XD3D8.cpp. Texture stage states that
are sampler states in Direct3D 9 map to D3DSAMP_*.

  python3 tools/gen_win32_states.py [path/to/d3d9types.h]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XBOX = os.path.join(ROOT, 'xbox', 'win32', 'include', 'd3d8types.h')
D3D9 = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/llvm-mingw/i686-w64-mingw32/include/d3d9types.h')


def enum_values(text, enum):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//.*', '', text)
    m = re.search(r'typedef enum _?%s\s*\{(.*?)\}' % enum, text, re.S)
    body = m.group(1)
    values, last = {}, -1
    for item in body.split(','):
        item = item.strip()
        if not item:
            continue
        if '=' in item:
            name, expr = [x.strip() for x in item.split('=', 1)]
            for k, v in values.items():
                expr = re.sub(r'\b%s\b' % k, str(v), expr)
            expr = re.sub(r'(\d+)L\b', r'\1', expr)
            try:
                last = eval(expr)
            except Exception:
                continue
        else:
            name = item
            last += 1
        values[name] = last
    return values


xbox = open(XBOX).read()
d3d9 = open(D3D9).read()
xrs = enum_values(xbox, 'D3DRENDERSTATETYPE')
xts = enum_values(xbox, 'D3DTEXTURESTAGESTATETYPE')
prs = enum_values(d3d9, 'D3DRENDERSTATETYPE')
pts = enum_values(d3d9, 'D3DTEXTURESTAGESTATETYPE')
psamp = enum_values(d3d9, 'D3DSAMPLERSTATETYPE')

out = ['// Generated by tools/gen_win32_states.py: the Xbox render and texture stage',
       '// states (index) and the Direct3D 9 ones of the same name.', '']
rs_max = xrs['D3DRS_MAX']
out.append('static const unsigned short kRenderStateMap[%d] = {' % rs_max)
names = {v: k for k, v in xrs.items() if k.startswith('D3DRS_') and not k.endswith(('_MIN', '_MAX')) and v < rs_max}
for i in range(rs_max):
    n = names.get(i)
    out.append('\t%d,   // %s' % (prs.get(n, 0) if n else 0, n or '-'))
out.append('};')
ts_max = xts['D3DTSS_MAX']
out.append('')
out.append('// (kind << 8) | number: kind 1 a texture stage state, 2 a sampler state.')
out.append('static const unsigned short kTextureStateMap[%d] = {' % ts_max)
names = {v: k for k, v in xts.items() if k.startswith('D3DTSS_') and not k.endswith('_MAX') and v < ts_max}
for i in range(ts_max):
    n = names.get(i)
    value = 0
    if n and n in pts:
        value = 0x100 | pts[n]
    elif n and n.replace('D3DTSS_', 'D3DSAMP_') in psamp:
        value = 0x200 | psamp[n.replace('D3DTSS_', 'D3DSAMP_')]
    out.append('\t0x%03X,   // %s' % (value, n or '-'))
out.append('};')
open(os.path.join(ROOT, 'xbox', 'win32', 'XD3DStates.inc'), 'w', newline='\n').write('\n'.join(out) + '\n')
print('render states %d, texture states %d' % (rs_max, ts_max))
